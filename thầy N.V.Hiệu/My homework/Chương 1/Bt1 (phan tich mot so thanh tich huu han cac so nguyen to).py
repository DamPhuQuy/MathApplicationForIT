import math

def is_prime(n):
    if n <= 1:
        return False
    for i in range(2, int(math.sqrt(n)) + 1):
        if n % i == 0:
            return False
    return True

def prime_factorize(n):
    primes = []
    exponents = []
    for x in range(2, int(math.sqrt(n)) + 1):
        if is_prime(x):
            if n % x == 0:
                count = 0
                while n % x == 0:
                    n //= x
                    count += 1
                primes.append(x)
                exponents.append(count)
    if n > 1:
        primes.append(n)
        exponents.append(1)
    return primes, exponents

def main():
    n = int(input("Nhập vào số n: "))

    if is_prime(n):
        print(f"{n} là số nguyên tố!")
    else:
        print(f"{n} không phải là số nguyên tố!")

    primes, exponents = prime_factorize(n)

    print(f"Tích các thừa số nguyên tố của {n} là:")
    print(f"{n} =", end=" ")
    for i in range(len(primes)):
        print(f"{primes[i]}", end="")
        if exponents[i] > 1:
            print(f"^{exponents[i]}", end="")
        if i < len(primes) - 1:
            print(" * ", end="")
    print()

if __name__ == "__main__":
    main()