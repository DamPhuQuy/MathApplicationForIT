import numpy as np

def is_square(matrix):
    """Check if the matrix is square."""
    return matrix.shape[0] == matrix.shape[1]

def is_symmetric(matrix):
    """Check if the matrix is symmetric."""
    return np.allclose(matrix, matrix.T)

def is_positive_definite(matrix):
    """Check if the matrix is positive definite by checking if all eigenvalues are positive."""
    eigenvalues = np.linalg.eigvals(matrix)
    return np.all(eigenvalues > 0)

def cholesky_decomposition_manual(matrix):
    """Compute Cholesky decomposition manually using the provided formulas."""
    n = matrix.shape[0]
    L = np.zeros((n, n))

    for i in range(n):
        for j in range(i + 1):
            if i == j:
                # Compute diagonal elements
                sum1 = np.sum(L[i, :j] ** 2)
                L[i, i] = np.sqrt(matrix[i, i] - sum1)
            else:
                # Compute off-diagonal elements
                sum2 = np.sum(L[i, :j] * L[j, :j])
                L[i, j] = (matrix[i, j] - sum2) / L[j, j]

    return L

def print_matrix(matrix, name):
    """Print the matrix in a formatted manner."""
    print(f"\n{name}:")
    print(np.array2string(matrix, precision=4, suppress_small=True))

def main():
    # Nhập kích thước của ma trận vuông
    n = int(input("Nhập kích thước của ma trận vuông (n): "))

    # Nhập ma trận A từ người dùng
    print("Nhập ma trận A:")
    A = np.zeros((n, n))
    for i in range(n):
        for j in range(n):
            A[i, j] = float(input(f"A[{i+1},{j+1}]: "))

    # Kiểm tra các điều kiện
    if not is_square(A):
        print("\nMa trận không phải là ma trận vuông.")
        return

    if not is_symmetric(A):
        print("\nMa trận không phải là ma trận đối xứng.")
        return

    if not is_positive_definite(A):
        print("\nMa trận không phải là ma trận dương định.")
        return

    # Thực hiện phân rã Cholesky
    try:
        L = cholesky_decomposition_manual(A)
        print_matrix(A, "Ma trận A")
        print_matrix(L, "Ma trận L")
        # Kiểm tra tính chính xác của phân rã Cholesky
        A_reconstructed = np.dot(L, L.T)
        print_matrix(A_reconstructed, "Ma trận tái tạo từ phân rã Cholesky")
    except np.linalg.LinAlgError as e:
        print("\nLỗi phân rã Cholesky:", e)

if __name__ == "__main__":
    main()