import numpy as np

def calculate_eigen(A):
    """Tính trị riêng và vectơ riêng của ma trận A."""
    eigenvalues, eigenvectors = np.linalg.eig(A)
    return eigenvalues, eigenvectors

def print_eigenvalues(eigenvalues):
    """In trị riêng."""
    print("\nTrị riêng:")
    for i, val in enumerate(eigenvalues):
        print(f"λ_{i+1} = {val:.5f}")

def print_eigenvectors_with_error(A, eigenvalues, eigenvectors, tol=1e-5):
    """In các vectơ riêng với sai số nhỏ hơn hoặc bằng sai số cho phép và làm tròn đến 5 chữ số thập phân."""
    print("\nVectơ riêng: ")
    for i in range(len(eigenvalues)):
        lambda_i = eigenvalues[i]
        v_i = eigenvectors[:, i]
        residual = np.dot(A, v_i) - lambda_i * v_i
        error = np.linalg.norm(residual)
        if error <= tol:
            v_i_rounded = np.round(v_i, 5)  # Làm tròn các giá trị của vectơ riêng đến 5 chữ số thập phân
            print(f"v_{i+1} =", v_i_rounded)
        else:
            print(f"Cặp trị riêng λ_{i+1} và vectơ riêng v_{i+1} vượt quá sai số cho phép {tol}.")

def check_determinant(A, tol=1e-5):
    """Kiểm tra xem định thức của ma trận A có khác 0 với sai số cho phép hay không."""
    det = np.linalg.det(A)
    if abs(det) < tol:
        print(f"Ma trận có định thức xấp xỉ 0 (|{det:.8f}| < {tol}). Không thể tính trị riêng và vectơ riêng.")
        return False
    return True

def main():
    # Nhập kích thước của ma trận vuông
    n = int(input("Nhập kích thước của ma trận vuông (n): "))

    # Nhập ma trận A từ người dùng
    print("Nhập ma trận A:")
    A = np.zeros((n, n))
    for i in range(n):
        for j in range(n):
            A[i, j] = float(input(f"A[{i+1},{j+1}]: "))

    # Kiểm tra định thức của ma trận với ngưỡng sai số 10^-5
    if check_determinant(A):
        # Tính toán các trị riêng và vectơ riêng
        eigenvalues, eigenvectors = calculate_eigen(A)

        # In trị riêng và vectơ riêng
        print_eigenvalues(eigenvalues)
        print_eigenvectors_with_error(A, eigenvalues, eigenvectors)

if __name__ == "__main__":
    main()
